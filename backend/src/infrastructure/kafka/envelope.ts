import { randomUUID } from 'node:crypto';

/**
 * The event envelope (Day 7).
 *
 * WHY AN ENVELOPE AT ALL
 * ----------------------
 * Kafka messages are just bytes. Without a shared envelope, every producer
 * invents its own shape and every consumer has to guess: is `id` the order or
 * the payment? was `timestamp` set by us or by the broker? The envelope splits
 * two concerns cleanly:
 *
 *   - the ENVELOPE is generic plumbing any consumer can handle blind
 *     (routing, dedup, tracing, dead-lettering);
 *   - the PAYLOAD is the domain-specific fact, understood only by consumers
 *     that care about that event type.
 *
 * That split is what lets a generic transport layer (consumer.ts, outbox.ts)
 * work for every event type without knowing what any of them mean.
 *
 * FIELD-BY-FIELD RATIONALE (every field earns its place)
 * -----------------------------------------------------
 *   eventId       Unique id for THIS fact. Two purposes: tracing one event
 *                 across producer → broker → consumer → DLQ, and DEDUPLICATION.
 *                 Kafka is at-least-once, so a consumer may see the same event
 *                 twice; eventId is the key the consumer records in its
 *                 processed-events ledger to make the second delivery a no-op.
 *                 It is generated by the PRODUCER (not the broker) so a
 *                 republish of the same logical event keeps the same id and is
 *                 still deduplicated downstream.
 *   eventType     What happened, in domain language ("OrderPaid"). Consumers
 *                 dispatch on this; it is also used for routing and metrics.
 *   eventVersion  Schema version of this event type. Additive changes stay at
 *                 v1; a breaking change ships a v2 old consumers can ignore,
 *                 instead of silently corrupting them.
 *   occurredAt    When the fact happened (ISO-8601, UTC) - a DOMAIN timestamp,
 *                 distinct from the broker's append time. Replaying a log
 *                 months later must not make events look like they just
 *                 happened, and late arrival must be detectable.
 *   aggregateType Which kind of thing this is about ('Order', 'Payment').
 *                 Enables generic handling ("everything for an order").
 *   aggregateId   Which instance (the order id / payment id). This is the
 *                 business identifier a consumer needs to act, as a string so
 *                 any identifier scheme works.
 *   partitionKey  NOT the same as aggregateId - see events.ts. It decides the
 *                 partition, and therefore what is ordered relative to what.
 *   correlationId Ties together everything caused by one user action. One
 *                 payment attempt can produce several events; they all share a
 *                 correlationId, which makes "show me everything from that
 *                 request" possible.
 *   producer      Which module emitted it, so ownership is clear without
 *                 reading the payload.
 *   payload       The domain fact itself. Deliberately excludes anything a
 *                 consumer does not need - and NEVER contains secrets.
 *
 * WHAT MUST NEVER GO IN HERE (docs/KAFKA.md §4)
 * --------------------------------------------
 * Passwords/hashes, JWTs, API keys, card data - anything you would not want
 * sitting in a topic log for seven days. A topic is not a secure channel by
 * default, and retention means "deleted" is a promise, not a click. Events
 * therefore carry internal numeric ids instead of emails/names, keeping the log
 * low-PII.
 */

/** Bump only for breaking changes to a payload shape. */
export const EVENT_ENVELOPE_VERSION = 1;

/** Event types that exist today. Add here when a new one is introduced. */
export const EVENT_TYPES = ['OrderPaid', 'PaymentFailed'] as const;

export type EventType = (typeof EVENT_TYPES)[number];

/** Aggregate kinds an event can be about. */
export const AGGREGATE_TYPES = ['Order', 'Payment'] as const;

export type AggregateType = (typeof AGGREGATE_TYPES)[number];

export interface EventEnvelope<TPayload = Record<string, unknown>> {
  eventId: string;
  eventType: EventType;
  eventVersion: number;
  occurredAt: string;
  aggregateType: AggregateType;
  aggregateId: string;
  partitionKey: string;
  correlationId: string;
  producer: string;
  payload: TPayload;
}

/** Everything the envelope factory needs; ids and timestamps are added here. */
export interface EnvelopeInput<TPayload> {
  eventType: EventType;
  aggregateType: AggregateType;
  aggregateId: string | number;
  partitionKey: string;
  producer: string;
  payload: TPayload;
  /**
   * Pass an existing correlationId to join a flow that is already in progress
   * (e.g. both events from one payment attempt share one id). Omitted = this
   * event starts a new flow and becomes its own correlation root.
   */
  correlationId?: string;
  /** Only for re-emitting an event that already has an id. Default: fresh id. */
  eventId?: string;
  /** Domain time of the fact. Default: now. */
  occurredAt?: Date;
}

/**
 * Builds a complete envelope. Centralised so no producer can forget a field or
 * invent its own timestamp format - every event in the system is shaped here.
 */
export function createEnvelope<TPayload>(input: EnvelopeInput<TPayload>): EventEnvelope<TPayload> {
  const eventId = input.eventId ?? randomUUID();
  return {
    eventId,
    eventType: input.eventType,
    eventVersion: EVENT_ENVELOPE_VERSION,
    occurredAt: (input.occurredAt ?? new Date()).toISOString(),
    aggregateType: input.aggregateType,
    aggregateId: String(input.aggregateId),
    partitionKey: input.partitionKey,
    // A flow's correlation root is its own eventId.
    correlationId: input.correlationId ?? eventId,
    producer: input.producer,
    payload: input.payload,
  };
}

function isNonEmptyString(value: unknown): value is string {
  return typeof value === 'string' && value.length > 0;
}

/**
 * Structural check for an envelope, used by the consumer BEFORE it trusts a
 * message. A malformed message is a PERMANENT failure: treating it as
 * retryable would burn the retry budget and dead-letter it anyway, one delay
 * at a time.
 */
export function isEventEnvelope(value: unknown): value is EventEnvelope {
  if (typeof value !== 'object' || value === null) return false;
  const candidate = value as Record<string, unknown>;

  return (
    isNonEmptyString(candidate.eventId) &&
    isNonEmptyString(candidate.eventType) &&
    typeof candidate.eventVersion === 'number' &&
    isNonEmptyString(candidate.occurredAt) &&
    isNonEmptyString(candidate.aggregateType) &&
    isNonEmptyString(candidate.aggregateId) &&
    isNonEmptyString(candidate.partitionKey) &&
    isNonEmptyString(candidate.correlationId) &&
    isNonEmptyString(candidate.producer) &&
    typeof candidate.payload === 'object' &&
    candidate.payload !== null
  );
}

/**
 * Deserializes a Kafka message value. Returns null (never throws) when the
 * bytes are not a valid envelope, so the caller can dead-letter rather than
 * crashing the consumer.
 */
export function parseEnvelope(raw: unknown): EventEnvelope | null {
  if (raw === null || raw === undefined) return null;
  const text = Buffer.isBuffer(raw) ? raw.toString('utf8') : String(raw);
  try {
    const parsed: unknown = JSON.parse(text);
    return isEventEnvelope(parsed) ? parsed : null;
  } catch {
    return null;
  }
}

/**
 * Event metadata as Kafka HEADERS.
 *
 * The envelope is already in the message body, so this is duplication -
 * deliberately. Headers let an operator (or a future routing/filtering step)
 * see what a message is about using tooling that never deserializes the
 * payload, which is exactly what you want when triaging a DLQ at 3am.
 *
 * Takes `EventEnvelope<unknown>` rather than the default payload type: this
 * function reads only the metadata fields and never touches `payload`, so it
 * must accept envelopes built for any payload shape (the outbox and the
 * consumer both hand it loosely-typed envelopes).
 */
export function envelopeHeaders(envelope: EventEnvelope<unknown>): Record<string, string> {
  return {
    eventId: envelope.eventId,
    eventType: envelope.eventType,
    eventVersion: String(envelope.eventVersion),
    occurredAt: envelope.occurredAt,
    aggregateType: envelope.aggregateType,
    aggregateId: envelope.aggregateId,
    correlationId: envelope.correlationId,
    producer: envelope.producer,
  };
}

